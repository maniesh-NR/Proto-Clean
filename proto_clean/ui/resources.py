def app_icon(size: int = 64) -> QIcon:
    """Proto Clean logo: shield + network triangle + padlock, matching
    docs/logo.png (embedded so frozen builds need no data files)."""
    pm = QPixmap()
    pm.loadFromData(base64.b64decode(_APP_ICON_PNG), "PNG")
    if pm.isNull():            # fallback: flat green shield
        return shield_icon("#2f6d3f", size)
    if size:
        pm = pm.scaled(size, size, Qt.KeepAspectRatio,
                       Qt.SmoothTransformation)
    return QIcon(pm)


def bolt_icon(color: str = "#f59e0b", size: int = 64) -> QPixmap:
    pm = _pixmap(size)
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    pts = [QPoint(int(size * .55), int(size * .08)), QPoint(int(size * .25), int(size * .55)),
           QPoint(int(size * .47), int(size * .55)), QPoint(int(size * .40), int(size * .92)),
           QPoint(int(size * .75), int(size * .42)), QPoint(int(size * .52), int(size * .42))]
    path = QPainterPath()
    path.moveTo(pts[0])
    for pt in pts[1:]:
        path.lineTo(pt)
    path.closeSubpath()
    p.fillPath(path, QColor(color))
    p.end()
    return pm
